const fs = require('fs');
const path = require('path');
const solc = require('solc');

function findImports(importPath) {
  if (importPath.startsWith('@openzeppelin/')) {
    const fullPath = path.resolve(__dirname, '..', 'node_modules', importPath);
    if (fs.existsSync(fullPath)) {
      return { contents: fs.readFileSync(fullPath, 'utf8') };
    }
  }
  const localPath = path.resolve(__dirname, '..', 'contracts', importPath);
  if (fs.existsSync(localPath)) {
    return { contents: fs.readFileSync(localPath, 'utf8') };
  }
  return { error: 'File not found: ' + importPath };
}

const contractSource = fs.readFileSync(
  path.resolve(__dirname, '..', 'contracts', 'FundTrailMilestoneEscrow.sol'),
  'utf8'
);

const input = {
  language: 'Solidity',
  sources: {
    'FundTrailMilestoneEscrow.sol': {
      content: contractSource,
    },
  },
  settings: {
    optimizer: {
      enabled: true,
      runs: 200,
    },
    outputSelection: {
      '*': {
        '*': ['abi', 'evm.bytecode.object'],
      },
    },
  },
};

console.log('Compiling FundTrailMilestoneEscrow.sol with solc 0.8.24...');
const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));

if (output.errors) {
  let hasError = false;
  output.errors.forEach((err) => {
    if (err.severity === 'error') {
      hasError = true;
      console.error(err.formattedMessage);
    } else {
      console.warn(err.formattedMessage);
    }
  });
  if (hasError) process.exit(1);
}

const contract = output.contracts['FundTrailMilestoneEscrow.sol']['FundTrailMilestoneEscrow'];
const artifact = {
  contractName: 'FundTrailMilestoneEscrow',
  abi: contract.abi,
  bytecode: contract.evm.bytecode.object,
};

const artifactsDir = path.resolve(__dirname, '..', 'artifacts');
if (!fs.existsSync(artifactsDir)) {
  fs.mkdirSync(artifactsDir, { recursive: true });
}
fs.writeFileSync(
  path.resolve(artifactsDir, 'FundTrailMilestoneEscrow.json'),
  JSON.stringify(artifact, null, 2)
);

// Also generate TypeScript ABI file in src/features/blockchain
const tsAbiPath = path.resolve(
  __dirname,
  '..',
  'src',
  'features',
  'blockchain',
  'milestone-escrow-abi.ts'
);
const tsContent = `// Auto-generated by scripts/compile.cjs\nexport const FUNDTRAIL_MILESTONE_ESCROW_ABI = ${JSON.stringify(contract.abi, null, 2)} as const;\n\nexport const FUNDTRAIL_MILESTONE_ESCROW_BYTECODE = "0x${contract.evm.bytecode.object}";\n`;
fs.writeFileSync(tsAbiPath, tsContent);

console.log('Compilation successful!');
console.log('Artifact saved to:', path.resolve(artifactsDir, 'FundTrailMilestoneEscrow.json'));
console.log('TypeScript ABI exported to:', tsAbiPath);

